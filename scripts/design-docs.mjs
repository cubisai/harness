// Generates docs/design/tokens.md from the design tokens in app.css, and
// checks (--check) that the committed doc is not stale. Pure, deterministic,
// EOL-normalised so it behaves the same on Windows and POSIX.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const BANNER = "<!-- GENERATED by scripts/design-docs.mjs from src/renderer/src/styles/app.css. Do not edit: change app.css, then run `bun run design:docs`. -->";

const LAYER_ORDER = ["color", "effect", "type", "shape", "layout", "motion", "other"];
const LAYER_TITLES = {
  color: "Color",
  effect: "Effect",
  type: "Type",
  shape: "Shape",
  layout: "Layout",
  motion: "Motion",
  other: "Other",
};

/** Normalise CRLF and lone CR line endings to LF. */
export function normalizeEol(text) {
  return text.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

/** Classify a token name into its design layer; first matching rule wins. */
export function layerOf(name) {
  if (name.startsWith("--font") || name === "--mono") return "type";
  if (name.startsWith("--radius")) return "shape";
  if (name === "--titlebar" || name === "--sidebar-w" || name === "--inspector-w" || name === "--zoom") return "layout";
  if (name.startsWith("--ease") || name.startsWith("--duration")) return "motion";
  if (name.startsWith("--shadow") || name.startsWith("--beam") || name.startsWith("--goo") || name.startsWith("--send-")) return "effect";
  if (
    name.startsWith("--bg") ||
    name.startsWith("--text") ||
    name.startsWith("--hairline") ||
    name.startsWith("--primary") ||
    name.startsWith("--on-") ||
    name.startsWith("--focus") ||
    name.startsWith("--signal") ||
    name === "--success" ||
    name === "--danger" ||
    name === "--warning" ||
    name.startsWith("--add") ||
    name.startsWith("--del")
  ) {
    return "color";
  }
  return "other";
}

/** Parse the design tokens out of an app.css source string. */
export function parseTokens(css) {
  const src = normalizeEol(css);
  const stripped = stripComments(src);
  const blocks = collectBlocks(stripped);

  const rootDecls = [];
  const rootIndex = new Map();
  const systemDark = new Map();
  const forcedDark = new Map();

  for (const block of blocks) {
    const role = classifyBlock(block);
    if (role === null) continue;
    const body = stripped.slice(block.bodyStart, block.bodyEnd);
    for (const decl of parseDeclarations(body)) {
      if (role === "root") {
        const existing = rootIndex.get(decl.name);
        const line = lineAt(stripped, block.bodyStart + decl.index);
        if (existing === undefined) {
          rootIndex.set(decl.name, rootDecls.length);
          rootDecls.push({ name: decl.name, value: decl.value, line });
        } else {
          rootDecls[existing].value = decl.value;
          rootDecls[existing].line = line;
        }
      } else if (role === "systemDark") {
        systemDark.set(decl.name, decl.value);
      } else {
        forcedDark.set(decl.name, decl.value);
      }
    }
  }

  return rootDecls.map((decl) => {
    const lightDark = parseLightDark(decl.value);
    const light = lightDark ? lightDark.light : decl.value;
    const dark = lightDark ? lightDark.dark : forcedDark.has(decl.name) ? forcedDark.get(decl.name) : null;
    const sys = lightDark ? lightDark.dark : systemDark.has(decl.name) ? systemDark.get(decl.name) : null;
    return { name: decl.name, light, dark, systemDark: sys, line: decl.line, layer: layerOf(decl.name) };
  });
}

/** Render the token reference markdown for an app.css source string. */
export function generateTokensMd(css) {
  const tokens = parseTokens(css);
  const lines = [BANNER, "", "# Design tokens", ""];
  lines.push(
    "`src/renderer/src/styles/app.css` is the only place token values are edited; this file is a generated cache checked by `bun run design:check`; components use `var(--token)`, never literals.",
  );

  for (const layer of LAYER_ORDER) {
    const group = tokens.filter((token) => token.layer === layer);
    if (group.length === 0) continue;
    lines.push("", `## ${LAYER_TITLES[layer]}`, "", "| Token | Light | Dark | Line |", "| --- | --- | --- | --- |");
    for (const token of group) {
      const dark = token.dark === null ? "—" : `\`${token.dark}\``;
      lines.push(`| \`${token.name}\` | \`${token.light}\` | ${dark} | ${token.line} |`);
    }
  }

  const aliases = [];
  for (const token of tokens) {
    const lightTarget = aliasTarget(token.light);
    if (lightTarget !== null) aliases.push(`- \`${token.name}\` → \`${lightTarget}\` (light)`);
    if (token.dark !== null) {
      const darkTarget = aliasTarget(token.dark);
      if (darkTarget !== null) aliases.push(`- \`${token.name}\` → \`${darkTarget}\` (dark)`);
    }
  }
  if (aliases.length > 0) lines.push("", "## Aliases", "", ...aliases);

  const drift = tokens.filter((token) => token.systemDark !== null && token.systemDark !== token.dark);
  if (drift.length > 0) {
    lines.push("", "## Theme drift", "");
    for (const token of drift) {
      const forced = token.dark === null ? "—" : `\`${token.dark}\``;
      lines.push(`- \`${token.name}\` — system dark \`${token.systemDark}\`, forced dark ${forced}`);
    }
  }

  return lines.join("\n") + "\n";
}

/** Blank out CSS comments with spaces, preserving newlines so line numbers hold. */
function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, (match) => match.replace(/[^\n]/g, " "));
}

/** Collect every brace block with its selector and dark-media ancestry. */
function collectBlocks(css) {
  const blocks = [];
  const stack = [];
  let preludeStart = 0;
  for (let i = 0; i < css.length; i++) {
    const ch = css[i];
    if (ch === "{") {
      const selector = css.slice(preludeStart, i).trim();
      const parent = stack[stack.length - 1];
      const opensDarkMedia = /^@media\b/.test(selector) && /prefers-color-scheme\s*:\s*dark/.test(selector);
      const block = {
        selector,
        inDarkMedia: (parent ? parent.inDarkMedia : false) || opensDarkMedia,
        bodyStart: i + 1,
        bodyEnd: -1,
      };
      stack.push(block);
      blocks.push(block);
      preludeStart = i + 1;
    } else if (ch === "}") {
      const block = stack.pop();
      if (block) block.bodyEnd = i;
      preludeStart = i + 1;
    }
  }
  return blocks;
}

/** Map a block selector to a token source, or null when it is not one. */
function classifyBlock(block) {
  if (block.inDarkMedia) return block.selector === ':root:not([data-theme="light"])' ? "systemDark" : null;
  if (block.selector === ":root") return "root";
  if (block.selector === ':root[data-theme="dark"]') return "forcedDark";
  return null;
}

/** Read `--name: value` declarations from a block body, ignoring everything else. */
function parseDeclarations(body) {
  const out = [];
  let i = 0;
  while (i < body.length) {
    while (i < body.length && (body[i] === ";" || /\s/.test(body[i]))) i++;
    if (i >= body.length) break;
    const start = i;
    const colon = findColon(body, i);
    if (colon === -1 || body[colon] !== ":") {
      if (colon === -1) break;
      i = colon + 1;
      continue;
    }
    const name = body.slice(start, colon).trim();
    const valueStart = colon + 1;
    const end = findDeclarationEnd(body, valueStart);
    const value = body.slice(valueStart, end).trim();
    if (name.startsWith("--")) out.push({ name, value, index: start });
    i = end + 1;
  }
  return out;
}

/** Find the next top-level `:` or `;` from `from`, honouring nested parens and quotes. */
function findColon(body, from) {
  let depth = 0;
  let quote = null;
  for (let i = from; i < body.length; i++) {
    const ch = body[i];
    if (quote !== null) {
      if (ch === "\\") {
        i++;
        continue;
      }
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === "(") depth++;
    else if (ch === ")") depth--;
    else if (depth === 0 && (ch === ":" || ch === ";" || ch === "{")) return i;
  }
  return -1;
}

/** Find the next top-level `;` from `from`, honouring nested parens and quotes. */
function findDeclarationEnd(body, from) {
  let depth = 0;
  let quote = null;
  for (let i = from; i < body.length; i++) {
    const ch = body[i];
    if (quote !== null) {
      if (ch === "\\") {
        i++;
        continue;
      }
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === "(") depth++;
    else if (ch === ")") depth--;
    else if (depth === 0 && ch === ";") return i;
  }
  return body.length;
}

/** Split a value at top-level commas, respecting nested parentheses and quotes. */
function splitTopLevel(input, separator) {
  const parts = [];
  let depth = 0;
  let quote = null;
  let current = "";
  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (quote !== null) {
      current += ch;
      if (ch === "\\") {
        current += input[++i] ?? "";
        continue;
      }
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === "(") depth++;
    else if (ch === ")") depth--;
    if (ch === separator && depth === 0) {
      parts.push(current);
      current = "";
      continue;
    }
    current += ch;
  }
  parts.push(current);
  return parts;
}

/** Collapse runs of whitespace to single spaces and trim. */
function tidy(value) {
  return value.replace(/\s+/g, " ").trim();
}

/** Parse `light-dark(light, dark)` into its two trimmed arguments, or null. */
function parseLightDark(value) {
  const prefix = "light-dark(";
  if (!value.startsWith(prefix) || !value.endsWith(")")) return null;
  const parts = splitTopLevel(value.slice(prefix.length, -1), ",");
  if (parts.length !== 2) return null;
  return { light: tidy(parts[0]), dark: tidy(parts[1]) };
}

/** Return the referenced token when a value is exactly `var(--name)`, else null. */
function aliasTarget(value) {
  const match = /^var\(\s*(--[\w-]+)\s*\)$/.exec(value);
  return match ? match[1] : null;
}

/** 1-based line number of `index` in `text`. */
function lineAt(text, index) {
  let line = 1;
  for (let i = 0; i < index && i < text.length; i++) {
    if (text[i] === "\n") line++;
  }
  return line;
}

/** Render a path relative to the repo root with forward slashes. */
function toPosix(path) {
  return path.split("\\").join("/");
}

/** CLI entry: write the doc, or check it with --check. */
function main() {
  const repoRoot = fileURLToPath(new URL("..", import.meta.url));
  const cssPath = join(repoRoot, "src", "renderer", "src", "styles", "app.css");
  const docPath = join(repoRoot, "docs", "design", "tokens.md");
  const rel = toPosix(relative(repoRoot, docPath));
  const css = readFileSync(cssPath, "utf8");

  if (process.argv.includes("--check")) {
    let existing = null;
    try {
      existing = readFileSync(docPath, "utf8");
    } catch {
      existing = null;
    }
    if (existing === null || normalizeEol(existing) !== generateTokensMd(css)) {
      console.error(`${rel} is stale; regenerate with bun run design:docs`);
      process.exit(1);
    }
    console.log(`${rel} is up to date`);
    process.exit(0);
  }

  const generated = generateTokensMd(css);
  mkdirSync(dirname(docPath), { recursive: true });
  writeFileSync(docPath, generated);
  console.log(`wrote ${rel} (${parseTokens(css).length} tokens)`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
