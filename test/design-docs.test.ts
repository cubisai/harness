import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { generateTokensMd, layerOf, normalizeEol, parseTokens } from "../scripts/design-docs.mjs";

const CSS = [
  "/* fake token --x: 1; must be ignored */",
  ":root {",
  "  --bg: #ffffff;",
  "  --primary: #0b0d10;",
  "  --radius-m: 8px;",
  "  --success: #2f9e44;",
  "  --send-fg: var(--text);",
  "  --mix: light-dark(rgb(1 2 3 / 0.5), #000000);",
  "  --drift: #000000;",
  "}",
  ":root {",
  '  --font: "Geist";',
  "  --text: #0b0d10;",
  "}",
  ".beam { --beam-edge: 2px; }",
  "@media (prefers-color-scheme: dark) {",
  '  :root:not([data-theme="light"]) {',
  "    --primary: #f7f8fa;",
  "    --text: #f7f8fa;",
  "    --drift: #111111;",
  "  }",
  "}",
  ':root[data-theme="dark"] {',
  "  --primary: #f7f8fa;",
  "  --text: #f7f8fa;",
  "  --drift: #222222;",
  "}",
  '@property --beam-angle { syntax: "<angle>"; }',
].join("\n");

const BANNER =
  "<!-- GENERATED by scripts/design-docs.mjs from src/renderer/src/styles/app.css. Do not edit: change app.css, then run `bun run design:docs`. -->";

describe("parseTokens", () => {
  const tokens = parseTokens(CSS);
  const byName = new Map(tokens.map((token) => [token.name, token]));

  it("merges :root blocks in source order and reads all three layers", () => {
    expect(tokens.map((token) => token.name)).toEqual([
      "--bg",
      "--primary",
      "--radius-m",
      "--success",
      "--send-fg",
      "--mix",
      "--drift",
      "--font",
      "--text",
    ]);
    expect(byName.get("--bg")).toMatchObject({ light: "#ffffff", dark: null, systemDark: null, line: 3, layer: "color" });
    expect(byName.get("--primary")).toMatchObject({ light: "#0b0d10", dark: "#f7f8fa", systemDark: "#f7f8fa", line: 4 });
    expect(byName.get("--radius-m")).toMatchObject({ light: "8px", dark: null, systemDark: null, line: 5, layer: "shape" });
    expect(byName.get("--success")).toMatchObject({ light: "#2f9e44", dark: null, systemDark: null, line: 6 });
    expect(byName.get("--font")).toMatchObject({ light: '"Geist"', dark: null, systemDark: null, line: 12, layer: "type" });
    expect(byName.get("--text")).toMatchObject({ light: "#0b0d10", dark: "#f7f8fa", systemDark: "#f7f8fa", line: 13, layer: "color" });
  });

  it("splits light-dark() at the top-level comma, respecting nested parens", () => {
    expect(byName.get("--mix")).toMatchObject({
      light: "rgb(1 2 3 / 0.5)",
      dark: "#000000",
      systemDark: "#000000",
      line: 8,
      layer: "other",
    });
  });

  it("ignores commented-out tokens and component-scoped vars", () => {
    expect(tokens.some((token) => token.name === "--x")).toBe(false);
    expect(tokens.some((token) => token.name === "--beam-edge")).toBe(false);
  });

  it("treats CRLF input identically to LF input", () => {
    expect(parseTokens(CSS.replace(/\n/g, "\r\n"))).toEqual(parseTokens(CSS));
    expect(generateTokensMd(CSS.replace(/\n/g, "\r\n"))).toBe(generateTokensMd(CSS));
  });
});

describe("layerOf", () => {
  it("applies the first matching rule", () => {
    expect(layerOf("--font")).toBe("type");
    expect(layerOf("--font-display")).toBe("type");
    expect(layerOf("--mono")).toBe("type");
    expect(layerOf("--radius-l")).toBe("shape");
    for (const name of ["--titlebar", "--sidebar-w", "--inspector-w", "--zoom"]) expect(layerOf(name)).toBe("layout");
    for (const name of ["--ease", "--duration-fast"]) expect(layerOf(name)).toBe("motion");
    for (const name of ["--shadow-float", "--beam-inner", "--goo-fill", "--send-bg"]) expect(layerOf(name)).toBe("effect");
    for (const name of [
      "--bg",
      "--text-secondary",
      "--hairline",
      "--primary-soft",
      "--on-primary",
      "--focus",
      "--signal-fill",
      "--success",
      "--danger",
      "--warning",
      "--add-bg",
      "--del-bg",
    ]) {
      expect(layerOf(name)).toBe("color");
    }
    expect(layerOf("--mix")).toBe("other");
  });
});

describe("normalizeEol", () => {
  it("normalises CRLF and lone CR to LF", () => {
    expect(normalizeEol("a\r\nb\rc\n")).toBe("a\nb\nc\n");
  });
});

describe("generateTokensMd", () => {
  const md = generateTokensMd(CSS);

  it("starts with the generated banner", () => {
    expect(md.startsWith(BANNER)).toBe(true);
    expect(md).toContain("# Design tokens");
  });

  it("ends with exactly one newline", () => {
    expect(md.endsWith("\n")).toBe(true);
    expect(md.endsWith("\n\n")).toBe(false);
  });

  it("emits layer sections in order and omits empty ones", () => {
    const positions = ["## Color", "## Effect", "## Type", "## Shape", "## Other"].map((heading) => md.indexOf(heading));
    for (const position of positions) expect(position).toBeGreaterThan(-1);
    expect(positions).toEqual([...positions].sort((a, b) => a - b));
    expect(md).not.toContain("## Layout");
    expect(md).not.toContain("## Motion");
  });

  it("renders null dark values as an em dash", () => {
    expect(md).toContain("| `--radius-m` | `8px` | — | 5 |");
  });

  it("lists aliases", () => {
    expect(md).toContain("## Aliases");
    expect(md).toContain("- `--send-fg` → `--text` (light)");
  });

  it("reports theme drift only when system dark and forced dark differ", () => {
    expect(md).toContain("## Theme drift");
    expect(md).toContain("`--drift`");
    const aligned = generateTokensMd(CSS.replace("--drift: #111111;", "--drift: #222222;"));
    expect(aligned).not.toContain("## Theme drift");
  });
});

describe("real app.css", () => {
  const css = readFileSync(join(__dirname, "..", "src", "renderer", "src", "styles", "app.css"), "utf8");
  const tokens = parseTokens(css);
  const byName = new Map(tokens.map((token) => [token.name, token]));

  it("exposes core tokens with their light values", () => {
    expect(byName.get("--bg")?.light).toBe("#ffffff");
    expect(byName.get("--primary")?.light).toBe("#0b0d10");
    expect(byName.get("--radius-m")?.light).toBe("8px");
    expect(byName.get("--radius-m")?.dark).toBeNull();
  });

  it("has no theme drift", () => {
    expect(generateTokensMd(css)).not.toContain("## Theme drift");
  });
});
