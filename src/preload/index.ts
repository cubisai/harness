import { contextBridge, ipcRenderer } from "electron";
import type { LiveUpdate, UnskilledApi } from "../shared/types";

const api: UnskilledApi = {
  platform: process.platform,
  opaqueSidebar: process.argv.includes("--opaque-sidebar"),
  smoke: process.argv.includes("--unskilled-smoke"),
  listProjects: () => ipcRenderer.invoke("projects:list"),
  addProject: () => ipcRenderer.invoke("projects:add"),
  deleteProject: (projectId) => ipcRenderer.invoke("projects:delete", projectId),
  listThreads: (projectId) => ipcRenderer.invoke("threads:list", projectId),
  createThread: (projectId, agent, opts) => ipcRenderer.invoke("threads:create", projectId, agent, opts),
  updateThread: (threadId, patch) => ipcRenderer.invoke("threads:update", threadId, patch),
  deleteThread: (threadId) => ipcRenderer.invoke("threads:delete", threadId),
  switchAgent: (threadId, agent, mode) => ipcRenderer.invoke("threads:switch", threadId, agent, mode),
  exportThread: (threadId) => ipcRenderer.invoke("threads:export", threadId),
  importThread: (projectId) => ipcRenderer.invoke("threads:import", projectId),
  exportSettings: () => ipcRenderer.invoke("settings:export"),
  importSettings: () => ipcRenderer.invoke("settings:import"),
  listEvents: (threadId) => ipcRenderer.invoke("events:list", threadId),
  listSkills: (projectId) => ipcRenderer.invoke("skills:list", projectId),
  listAgents: () => ipcRenderer.invoke("agents:list"),
  send: (request) => ipcRenderer.invoke("turn:send", request),
  interrupt: (threadId) => ipcRenderer.invoke("turn:interrupt", threadId),
  respondPermission: (requestId, decision) => ipcRenderer.invoke("permission:respond", requestId, decision),
  respondPlan: (requestId, decision) => ipcRenderer.invoke("plan:respond", requestId, decision),
  getDiff: (projectId, threadId) => ipcRenderer.invoke("diff:get", projectId, threadId),
  listFiles: (projectId, threadId) => ipcRenderer.invoke("files:list", projectId, threadId),
  projectBranch: (projectId) => ipcRenderer.invoke("project:branch", projectId),
  browserAttached: (webContentsId) => ipcRenderer.invoke("browser:attached", webContentsId),
  browserPick: () => ipcRenderer.invoke("browser:pick"),
  browserDevice: (preset) => ipcRenderer.invoke("browser:device", preset),
  browserState: () => ipcRenderer.invoke("browser:state"),
  browserTakeOver: (paused) => ipcRenderer.invoke("browser:takeover", paused),
  terminalOpen: (id, cwd, cols, rows) => ipcRenderer.invoke("terminal:open", id, cwd, cols, rows),
  terminalWrite: (id, data) => ipcRenderer.send("terminal:write", id, data),
  terminalResize: (id, cols, rows) => ipcRenderer.send("terminal:resize", id, cols, rows),
  terminalClose: (id) => ipcRenderer.invoke("terminal:close", id),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  updateSettings: (patch) => ipcRenderer.invoke("settings:update", patch),
  listProviders: () => ipcRenderer.invoke("providers:list"),
  saveProvider: (input, secret) => ipcRenderer.invoke("providers:save", input, secret),
  removeProvider: (id) => ipcRenderer.invoke("providers:remove", id),
  setProviderSecret: (id, value) => ipcRenderer.invoke("providers:secret", id, value),
  testProvider: (id, modelId) => ipcRenderer.invoke("providers:test", id, modelId),
  setCredential: (agentId, choice) => ipcRenderer.invoke("providers:setCredential", agentId, choice),
  openDataFolder: () => ipcRenderer.invoke("app:open-data-folder"),
  updateStatus: () => ipcRenderer.invoke("app:update-status"),
  aboutInfo: () => ipcRenderer.invoke("app:about"),
  contextPreview: (threadId, projectId) => ipcRenderer.invoke("context:preview", threadId, projectId),
  listLimits: () => ipcRenderer.invoke("limits:list"),
  listAllSkills: (projectId) => ipcRenderer.invoke("library:skills", projectId),
  getSkillDetail: (name, projectId) => ipcRenderer.invoke("library:skill", name, projectId),
  setSkillEnabled: (origin, name, enabled) => ipcRenderer.invoke("skills:set-enabled", origin, name, enabled),
  getSkillFolders: (projectId) => ipcRenderer.invoke("skills:folders", projectId),
  createSkill: (input) => ipcRenderer.invoke("skills:create", input),
  listAgentCatalog: () => ipcRenderer.invoke("library:agents"),
  getMcp: (projectId) => ipcRenderer.invoke("mcp:get", projectId),
  saveMcpServer: (entry, previousName, projectId) => ipcRenderer.invoke("mcp:save", entry, previousName, projectId),
  removeMcpServer: (name, projectId) => ipcRenderer.invoke("mcp:remove", name, projectId),
  setMcpServerEnabled: (name, enabled, projectId) => ipcRenderer.invoke("mcp:enable", name, enabled, projectId),
  testMcpServer: (name, projectId) => ipcRenderer.invoke("mcp:test", name, projectId),
  setGlobalMcpOff: (projectId, name, off) => ipcRenderer.invoke("mcp:global-off", projectId, name, off),
  revealPath: (path) => ipcRenderer.invoke("app:reveal", path),
  listEditors: () => ipcRenderer.invoke("editors:list"),
  openInEditor: (target, editor) => ipcRenderer.invoke("editors:open", target, editor),
  installUpdate: () => ipcRenderer.invoke("app:install-update"),
  onUpdate: (listener) => {
    const handler = (_e: Electron.IpcRendererEvent, update: LiveUpdate) => listener(update);
    ipcRenderer.on("unskilled:update", handler);
    return () => ipcRenderer.removeListener("unskilled:update", handler);
  },
};

contextBridge.exposeInMainWorld("unskilled", api);
