import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const HEADER = "// GENERATED by build.mjs from src/ - do not edit\n";
mkdirSync("dist", { recursive: true });
for (const name of readdirSync("src")) writeFileSync(`dist/${name}`, HEADER + readFileSync(`src/${name}`, "utf8"));
console.log("built dist/");
