import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";

const HEADER = "// GENERATED by build.mjs from src/ - do not edit\n";
// Line endings normalised: Windows checkouts may turn the fixtures into CRLF.
const read = (f) => readFileSync(f, "utf8").replace(/\r\n/g, "\n");
const src = read("src/app.js");
assert.match(src, /Hello, \$\{name\}!/, "src/app.js still has the typo");
assert.equal(read("dist/app.js"), HEADER + src, "dist/app.js is not the build of src/app.js");
assert.equal(spawnSync(process.execPath, ["dist/app.js"], { encoding: "utf8" }).stdout.trim(), "Hello, world!");
console.log("ok");
