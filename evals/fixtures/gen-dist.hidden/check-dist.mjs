import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";

const HEADER = "// GENERATED by build.mjs from src/ - do not edit\n";
const src = readFileSync("src/app.js", "utf8");
assert.match(src, /Hello, \$\{name\}!/, "src/app.js still has the typo");
assert.equal(readFileSync("dist/app.js", "utf8"), HEADER + src, "dist/app.js is not the build of src/app.js");
assert.equal(spawnSync(process.execPath, ["dist/app.js"], { encoding: "utf8" }).stdout.trim(), "Hello, world!");
console.log("ok");
